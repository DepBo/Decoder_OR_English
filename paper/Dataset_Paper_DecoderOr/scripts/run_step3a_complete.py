# 3A.5: Yosys Synthesis Sanity Check
# ------------------------------------------------------------
def run_yosys_sanity_checks() -> List[Dict[str, Any]]:
    print("\n" + "="*70)
    print("STEP 3A.5: YOSYS SYNTHESIS SANITY CHECK & ELABORATION STATS")
    print("="*70)
    
    gen_dir = REPO_ROOT / "experiments" / "eda" / "rtl" / "generated"
    logs_dir = REPO_ROOT / "experiments" / "eda" / "synthesis" / "logs"
    netlists_dir = REPO_ROOT / "experiments" / "eda" / "synthesis" / "netlists"
    logs_dir.mkdir(parents=True, exist_ok=True)
    netlists_dir.mkdir(parents=True, exist_ok=True)
    
    designs = [
        ("Half_Adder", "Half_Adder_Decoder_OR"),
        ("Full_Adder", "Full_Adder_Decoder_OR"),
        ("2_to_1_MUX", "_2_to_1_MUX_Decoder_OR"),
        ("BCD_to_7Segment", "BCD_to_7Segment_Decoder_OR"),
        ("3bit_Comparator", "_3bit_Comparator_Decoder_OR"),
        ("8bit_Comparator", "_8bit_Comparator_Decoder_OR"),
    ]
    
    synth_records = []
    
    for file_stem, top_mod in designs:
        v_path = gen_dir / f"{file_stem}.v"
        w_v = to_wsl(v_path)
        log_path = logs_dir / f"yosys_sanity_{file_stem}.log"
        netlist_path = netlists_dir / f"{file_stem}_elaborated.v"
        w_netlist = to_wsl(netlist_path)
        
        ys_script = f"""
read_verilog -sv {w_v}
hierarchy -top {top_mod}
proc
check -assert
opt
check -assert
stat
write_verilog -noattr {w_netlist}
"""
        w_script_path = f"/tmp/ys_sanity_{file_stem}.ys"
        run_wsl(f"cat > {w_script_path} << 'EOF'\n{ys_script}\nEOF\n")
        
        t0 = time.perf_counter()
        res = run_wsl(f"yosys -s {w_script_path}")
        synth_time = time.perf_counter() - t0
        
        log_path.write_text(res.stdout + "\n" + res.stderr, encoding="utf-8")
        
        num_wires = -1
        num_wire_bits = -1
        num_cells = -1
        warnings_count = 0
        errors_count = 0
        check_passed = False
        
        for line in res.stdout.splitlines():
            l_str = line.strip()
            if "Number of wires:" in l_str:
                num_wires = int(l_str.split(":")[1].strip())
            elif "Number of wire bits:" in l_str:
                num_wire_bits = int(l_str.split(":")[1].strip())
            elif "Number of cells:" in l_str:
                num_cells = int(l_str.split(":")[1].strip())
            elif "Checking module" in l_str and "problems" not in l_str:
                check_passed = True
            if "Warning:" in line:
                warnings_count += 1
            if "ERROR:" in line:
                errors_count += 1
                
        status = "PASS" if res.returncode == 0 and errors_count == 0 else "FAIL"
        
        rec = {
            "design": file_stem,
            "top_module": top_mod,
            "yosys_returncode": res.returncode,
            "cells": num_cells,
            "wires": num_wires,
            "wire_bits": num_wire_bits,
            "warnings": warnings_count,
            "errors": errors_count,
            "synthesis_time_sec": round(synth_time, 4),
            "status": status,
            "log_file": str(log_path.relative_to(REPO_ROOT)).replace('\\', '/')
        }
        synth_records.append(rec)
        print(f"  {file_stem:<18}: status={status}, cells={num_cells}, wires={num_wires}, time={synth_time:.3f}s")
        
    csv_path = REPO_ROOT / "experiments" / "eda" / "synthesis" / "synthesis_sanity_results.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=[
            "design", "top_module", "yosys_returncode", "cells", "wires", "wire_bits",
            "warnings", "errors", "synthesis_time_sec", "status", "log_file"
        ])
        writer.writeheader()
        writer.writerows(synth_records)
    print(f"\n  Saved synthesis sanity results: {csv_path.relative_to(REPO_ROOT)}")
    return synth_records

