WSL_PREFIX = ["wsl", "-e", "bash", "-c"]

def to_wsl(p: Path) -> str:
    s = str(p.resolve()).replace('\\', '/')
    if s[1] == ':':
        drive = s[0].lower()
        s = f"/mnt/{drive}{s[2:]}"
    return s

def run_wsl(cmd: str) -> subprocess.CompletedProcess:
    return subprocess.run(WSL_PREFIX + [cmd], capture_output=True, text=True)

